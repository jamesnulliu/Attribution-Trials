"""The trial against a known, dialled amount of individual signal.

Population.  Each user u draws a latent rate q_u ~ Beta(4, 2) (mean 2/3).
Their generating rate is

    p_u(lambda) = (1 - lambda) * qbar + lambda * q_u

so at lambda = 0 every user is generated by the same rate and there is no
individual information to find, while at lambda = 1 the population is fully
individual.  Each user emits N_TOTAL Bernoulli responses split 70/30 into
train and held-out.

Method.  The per-user Laplace-smoothed Bernoulli rate, scored under the
target's own rate (A4) and under a within-cell imposter's rate (A3).  Cells
are prior-accuracy tertiles of the training split; the imposter is the
seeded within-cell derangement.  `dindiv` is A4 minus A3 held-out NLL, so
negative favours the target (the paper's gain is its negation); a replicate
is a detection when its paired bootstrap interval lies below zero.

No language model is involved.

  python -m attribution_trials.validation.lambda_sweep
Output: <VALIDATION>/lambda_sweep.json
"""

from __future__ import annotations

import json

import numpy as np

from attribution_trials import paths
from attribution_trials.bench.swap import within_cell_derangement
from attribution_trials.eval.bootstrap import bootstrap_ci

N_USERS = 500
N_TOTAL = 100
TRAIN_FRAC = 0.7
ALPHA_BETA = (4.0, 2.0)
ALPHA_LAPLACE = 1.0
LAMBDAS = (0.0, 0.1, 0.25, 0.5, 0.75, 1.0)
REPLICATES = 200
BOOT_N = 2000
BASE_SEED = 20260817


def build_population(lam: float, seed: int) -> dict:
    """One synthetic cohort at identity-signal level `lam`."""
    rng = np.random.default_rng(seed)
    q = rng.beta(*ALPHA_BETA, size=N_USERS)
    qbar = ALPHA_BETA[0] / sum(ALPHA_BETA)
    p = (1.0 - lam) * qbar + lam * q

    n_train = int(N_TOTAL * TRAIN_FRAC)
    draws = rng.random((N_USERS, N_TOTAL)) < p[:, None]
    train, heldout = draws[:, :n_train], draws[:, n_train:]

    users = [f"u{i:04d}" for i in range(N_USERS)]
    train_correct = train.sum(axis=1).astype(float)
    own = (train_correct + ALPHA_LAPLACE) / (n_train + 2 * ALPHA_LAPLACE)
    train_accuracy = train_correct / n_train

    # prior-accuracy tertiles from the training split
    order = np.argsort(train_accuracy, kind="stable")
    cells = {}
    for rank, index in enumerate(order):
        cells[users[index]] = f"pacc_t{min(2, rank * 3 // N_USERS)}"

    imposter = within_cell_derangement(cells, seed=0)
    imposter_index = np.array([users.index(imposter[u]) for u in users])

    return {
        "heldout": heldout,
        "arm_rates": {
            "A3": own[imposter_index],
            "A4": own,
        },
    }


def bernoulli_nll(heldout: np.ndarray, rates: np.ndarray) -> np.ndarray:
    rate = np.clip(rates, 1e-9, 1 - 1e-9)[:, None]
    return -(heldout * np.log(rate) + (1 - heldout) * np.log(1 - rate)).mean(axis=1)


def dindiv(population: dict) -> np.ndarray:
    arms = {
        name: bernoulli_nll(population["heldout"], rates)
        for name, rates in population["arm_rates"].items()
    }
    return arms["A4"] - arms["A3"]


def main() -> None:
    summary_rows = []
    for lam in LAMBDAS:
        points, favourable = [], 0
        for replicate in range(REPLICATES):
            seed = BASE_SEED + int(lam * 1000) * 10000 + replicate
            delta = dindiv(build_population(lam, seed)).tolist()
            boot = bootstrap_ci(delta, n_resamples=BOOT_N, seed=0)
            favourable += boot.high < 0
            points.append(float(boot.point))
        points = np.array(points)
        summary_rows.append(
            {
                "lambda": lam,
                "replicates": REPLICATES,
                "dindiv_mean": float(points.mean()),
                "dindiv_sd": float(points.std(ddof=1)),
                "dindiv_q025": float(np.quantile(points, 0.025)),
                "dindiv_q975": float(np.quantile(points, 0.975)),
                "detection_rate": favourable / REPLICATES,
            }
        )
        print(
            f"  lambda={lam:<5} dindiv={points.mean():+.5f} "
            f"(sd {points.std(ddof=1):.5f})  "
            f"detected {favourable}/{REPLICATES} = "
            f"{favourable / REPLICATES:.3f}",
            flush=True,
        )

    monotone = all(
        summary_rows[i]["dindiv_mean"] >= summary_rows[i + 1]["dindiv_mean"]
        for i in range(len(summary_rows) - 1)
    )
    null_row = summary_rows[0]

    payload = {
        "meta": {
            "population": (
                f"{N_USERS} users, {N_TOTAL} Bernoulli responses each, "
                f"{TRAIN_FRAC:.0%} train; q ~ Beta{ALPHA_BETA}; "
                "p_u(lambda) = (1-lambda)*qbar + lambda*q_u"
            ),
            "method": (
                "per-user Laplace-smoothed Bernoulli, target (A4) vs "
                "within-cell imposter (A3), prior-accuracy tertile cells, "
                "within-cell derangement seed 0"
            ),
            "detection_rule": ("paired bootstrap interval of A4 - A3 lies below zero"),
            "replicates": REPLICATES,
            "ci": f"paired bootstrap {BOOT_N}",
        },
        "calibration": {
            "monotone_in_lambda": monotone,
            "null_false_positive_rate": null_row["detection_rate"],
            "null_dindiv_mean": null_row["dindiv_mean"],
            "nominal_alpha": 0.05,
        },
        "sweep": summary_rows,
    }
    out = paths.ensure(paths.VALIDATION) / "lambda_sweep.json"
    out.write_text(json.dumps(payload, indent=2) + "\n")
    print(json.dumps(payload["calibration"], indent=2))
    print(f"-> {out}")


if __name__ == "__main__":
    main()
